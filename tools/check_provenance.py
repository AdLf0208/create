#!/usr/bin/env python3
"""Prove that no packaged file or carried asset carries an upstream byte, and write the trail.

Create's code is MIT, but `src/main/resources/assets/` in the cached jar is **All Rights
Reserved** (verified from Creators-of-Create/Create `LICENSE.md`). Not one upstream texture,
model, lang file or icon may travel in this package. Every asset is generated by
`tools/gen_assets.py` from its own palette and re-authored 26.3 data.

This tool is the machine-checked half of that claim:

* it hashes every entry of the cached jar and every file under `assets/`, `data/` and `icon.png`;
* it hashes every file of the built `create.hmod`;
* `--check` fails if **any** candidate or packaged file's sha256 equals any jar entry's sha256
  (a copy under a different name is caught too — comparison is by content, not by path);
* without `--check` it also writes `PROVENANCE.md`, one line per packaged file.

    python3 tools/check_provenance.py            # assert, then write PROVENANCE.md
    python3 tools/check_provenance.py --check    # assert only (the ladder gate)

Exit 0 when clean, 1 on any jar-derived byte, 2 when the jar or package is missing.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import zipfile
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
PORTS = PORT.parent
DEFAULT_JAR = PORTS / "_shared" / "licence-cache" / "create-1.21.1-6.0.10.jar"
DEFAULT_HMOD = PORT / "create.hmod"
DEFAULT_REPORT = PORT / "PROVENANCE.md"

GENERATED = "generated (`tools/gen_assets.py`, deterministic palette and shapes)"
AUTHORED = "authored (this port's Rust, manifest, licence or prose)"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def jar_digests(jar: Path) -> dict[str, list[str]]:
    """sha256 -> the jar's paths with that content (a rename is still caught)."""
    found: dict[str, list[str]] = {}
    with zipfile.ZipFile(jar) as archive:
        for info in archive.infolist():
            if info.is_dir():
                continue
            found.setdefault(digest(archive.read(info)), []).append(info.filename)
    return found


def entries(hmod: Path) -> list[tuple[str, int, str]]:
    """Every file entry of the package, sorted by path."""
    out: list[tuple[str, int, str]] = []
    with zipfile.ZipFile(hmod) as archive:
        for info in archive.infolist():
            if info.is_dir():
                continue
            out.append((info.filename, info.file_size, digest(archive.read(info))))
    return sorted(out)


def candidates() -> list[Path]:
    """The files whose bytes could be jar-derived art: carried content and the icon."""
    out: list[Path] = []
    for root in ("assets", "data"):
        folder = PORT / root
        if folder.is_dir():
            out.extend(p for p in folder.rglob("*") if p.is_file())
    icon = PORT / "icon.png"
    if icon.is_file():
        out.append(icon)
    return sorted(out)


def classify(name: str) -> str:
    if name.startswith(("assets/", "data/")) or name == "icon.png":
        return GENERATED
    return AUTHORED


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--jar", type=Path, default=DEFAULT_JAR)
    parser.add_argument("--hmod", type=Path, default=DEFAULT_HMOD)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--check", action="store_true", help="assert only; write no report")
    args = parser.parse_args()

    for path, what in ((args.jar, "jar"), (args.hmod, "package")):
        if not path.is_file():
            print(f"missing {what}: {path}", file=sys.stderr)
            return 2

    jar = jar_digests(args.jar)
    packaged = entries(args.hmod)
    cand = candidates()

    offenders: list[str] = []
    for path in cand:
        rel = str(path.relative_to(PORT))
        match = jar.get(digest(path.read_bytes()))
        if match:
            offenders.append(f"tree {rel} == jar {match[0]}")
    for name, _size, sha in packaged:
        match = jar.get(sha)
        if match:
            offenders.append(f"package {name} == jar {match[0]}")

    if offenders:
        for line in offenders:
            print(f"FAIL: jar-derived byte: {line}", file=sys.stderr)
        print(f"FAIL: {len(offenders)} jar-derived file(s)", file=sys.stderr)
        return 1
    print(
        f"OK: zero jar-derived asset bytes — {len(cand)} candidate files, "
        f"{len(packaged)} packaged files, 0 matches against {len(jar)} jar entries"
    )
    if args.check:
        return 0

    lines = [
        "# Provenance — every packaged file is this port's own",
        "",
        "Create's **code is MIT**, but the `src/main/resources/assets/` tree of the cached jar is",
        "**All Rights Reserved** (Creators-of-Create/Create `LICENSE.md`). No upstream art, model,",
        "language file or icon travels in this package. Every carried asset is written by",
        "`tools/gen_assets.py` from the palette and shapes in that file; the 26.3 data files are",
        "re-authored from the jar's semantics, never copied. This report is generated by",
        "`tools/check_provenance.py`, which also proves the claim by hashing every file against",
        "every entry of the jar.",
        "",
        "| | |",
        "|---|---|",
        f"| jar | `{args.jar.name}` — {args.jar.stat().st_size:,} B, sha256 `{digest(args.jar.read_bytes())}` |",
        f"| package | `{args.hmod.name}` — {args.hmod.stat().st_size:,} B, sha256 `{digest(args.hmod.read_bytes())}`, {len(packaged)} files |",
        f"| candidate tree files | {len(cand)} |",
        "| files identical to a jar entry | **0** |",
        "",
        "## How each packaged file was produced",
        "",
        "| packaged file | bytes | provenance |",
        "|---|---:|---|",
    ]
    lines += [f"| `{name}` | {size:,} | {classify(name)} |" for name, size, _sha in packaged]
    lines += [
        "",
        "The monogram `icon.png` and every texture/model/blockstate/lang/data file come from",
        "`tools/gen_assets.py`; `--check` re-renders them and compares byte for byte. No Mojang",
        "file and no jar-derived byte is in the tree or the package.",
        "",
    ]
    args.report.write_text("\n".join(lines))
    print(f"wrote {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
